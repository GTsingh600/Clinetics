"""Synthetic data generator for Clinetics.

ALL DATA PRODUCED BY THIS SCRIPT IS SYNTHETIC. No real patient data is used,
read, or derived from. Names and contact details come from Faker; every
clinically meaningful distribution is generated by the explicit models below.

The point of this file is that the data must contain *genuinely learnable
structure*. Random noise would let the ML layer report metrics without those
metrics meaning anything. Every distribution below is therefore specified,
parameterised, and — critically — verified afterwards by
`scripts/validate_data.py`, which fails if the intended correlations are not
actually present in the generated rows.

================================================================================
1. NO-SHOW MODEL
================================================================================
A no-show is generated from a logistic model, not an i.i.d. coin flip:

    logit(p) = B0
             + B_LEAD     * log1p(lead_time_days)
             + B_DOW[weekday]
             + B_HOUR(hour_of_day)
             + patient_latent_offset
             + B_NEW_PATIENT * is_new_patient
             + B_URGENCY[urgency]

    B0                = -2.30   (baseline ~9% before any adjustment)
    B_LEAD            = +0.42   per unit log1p(days). Longer lead time means a
                                higher no-show rate, and the log makes the
                                effect saturate: days 0->7 matter far more than
                                days 30->37. This is the single strongest
                                predictor and the primary thing Phase 3 must
                                recover.
    B_DOW             = Mon +0.30, Tue -0.05, Wed -0.10, Thu 0.00,
                        Fri +0.22, Sat +0.15, Sun +0.10
                                Monday and Friday are worse, matching the
                                well-known start/end-of-week pattern.
    B_HOUR            = +0.34 at 08:00, falling to -0.12 around 12:00, rising
                        to +0.40 by 18:00 (piecewise linear via _hour_effect).
                                Early and late slots are missed more often.
    patient_latent    = logit(Beta(2.0, 8.0)) - logit(0.2), i.e. a per-patient
                        offset with mean ~0. Each patient carries a stable
                        propensity, so a patient's OWN HISTORY predicts their
                        future behaviour. Without this the "patient historical
                        no-show rate" feature would be pure noise.
    B_NEW_PATIENT     = +0.45   First-time patients are less committed.
    B_URGENCY         = routine 0.0, urgent -0.70, emergency -1.40
                                Sicker patients turn up.

Target aggregate no-show rate: 15-22%.

================================================================================
2. DEMAND MODEL
================================================================================
Appointment volume per (date, specialty, hour) is Poisson:

    lambda = BASE_DAILY[specialty]
           * WEEKDAY_MULT[weekday]
           * HOUR_PROFILE[specialty][hour]
           * (1 + SEASONAL_AMPLITUDE * sin(2*pi*(day_of_year - 20)/365))

    BASE_DAILY        cardiology 7.0, dermatology 6.0, general_practice 14.0,
                      orthopedics 5.5, pediatrics 8.0
    WEEKDAY_MULT      Mon 1.35, Tue 1.05, Wed 1.00, Thu 1.02, Fri 0.95,
                      Sat 0.45, Sun 0.10
                                Strong weekday/weekend split, with Monday the
                                busiest day.
    HOUR_PROFILE      per specialty, normalised over clinic hours:
                        * general_practice / cardiology / orthopedics:
                          morning-weighted, peaking 09:00-11:00
                        * dermatology: EVENING-weighted, peaking 16:00-18:00
                        * pediatrics: bimodal, peaking 09:00 and 15:00-16:00
                                Specialty-specific intra-day shape is what makes
                                an hourly forecast worth training at all.
    SEASONAL_AMPLITUDE = 0.15, annual sinusoid peaking in late winter.

================================================================================
3. DURATION MODEL
================================================================================
    duration = clip(round_to_5(LogNormal(mu=log(base), sigma=SIGMA)
                               + NEW_PATIENT_EXTRA * is_new_patient),
                    10, 120)

    base (minutes)    cardiology 35, dermatology 20, general_practice 15,
                      orthopedics 30, pediatrics 25
    SIGMA             0.28  (log-scale); right-skewed, as real consultations are
    NEW_PATIENT_EXTRA 8 minutes

================================================================================
4. LEAD TIME MODEL
================================================================================
    routine    lead ~ Gamma(shape=2.0, scale=7.0), clipped to [0, 90]
    urgent     lead ~ Gamma(shape=1.2, scale=2.0), clipped to [0, 14]
    emergency  lead = 0 with p=0.7, else Gamma(1.0, 1.0) clipped to [0, 3]

Urgency mix: routine 0.80, urgent 0.16, emergency 0.04.

================================================================================
5. CANCELLATION MODEL
================================================================================
Cancellation is decided BEFORE no-show (a cancelled appointment cannot also be
a no-show), and shares the lead-time driver:

    logit(p_cancel) = -2.60 + 0.30 * log1p(lead_time_days)

================================================================================
USAGE
================================================================================
    uv run python scripts/generate_data.py --months 12 --doctors 8 --patients 1500
    uv run python scripts/validate_data.py        # the gate; must pass next

`--reset` truncates all generated rows first. The script is deterministic for a
given `--seed`.
"""

