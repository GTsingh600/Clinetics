def reset_data(session: Session) -> None:
    log.info("truncating existing generated data")
    session.execute(
        text(
            "TRUNCATE analytics.schedule_entry, analytics.schedule, analytics.forecast, "
            "analytics.doctor_utilization, appointment, availability, doctor_specialty, "
            "room, doctor, patient, specialty, clinic, user_account RESTART IDENTITY CASCADE"
        )
    )
    session.commit()


def seed_reference_data(
    session: Session, fake: Faker, rng: random.Random, n_doctors: int
) -> tuple[Clinic, dict[str, Specialty], list[Doctor]]:
    clinic = Clinic(
        name="Clinetics Central",
        opens_at=dt.time(CLINIC_OPEN_HOUR, 0),
        closes_at=dt.time(CLINIC_CLOSE_HOUR, 0),
        timezone="UTC",
        address=fake.street_address(),
        phone=fake.phone_number()[:32],
    )
    session.add(clinic)
    session.flush()

    specialties: dict[str, Specialty] = {}
    for spec in SPECIALTIES:
        row = Specialty(
            name=spec.name,
            slug=spec.slug,
            default_duration_minutes=spec.base_duration,
            description=f"{spec.name} outpatient services",
        )
        session.add(row)
        session.flush()
        specialties[spec.slug] = row

    for i in range(1, 7):
        session.add(Room(clinic_id=clinic.id, name=f"Room {i}", capacity=1))

    # Distribute doctors across specialties, weighted by demand so the busiest
    # specialty has the most capacity. Without this the generator would produce
    # a schedule that is structurally impossible to satisfy.
    weights = [s.base_daily_volume for s in SPECIALTIES]
    doctors: list[Doctor] = []
    for i in range(n_doctors):
        primary = rng.choices(SPECIALTIES, weights=weights, k=1)[0]
        doctor = Doctor(
            clinic_id=clinic.id,
            first_name=fake.first_name(),
            last_name=fake.last_name(),
            license_number=f"LIC-{100000 + i}",
            is_active=True,
        )
        session.add(doctor)
        session.flush()
        session.execute(
            insert(doctor_specialty).values(
                doctor_id=doctor.id,
                specialty_id=specialties[primary.slug].id,
                is_primary=True,
            )
        )
        # ~35% of doctors hold a second, non-primary specialty. This is what
        # makes the many-to-many junction carry real information rather than
        # being a one-row-per-doctor table in disguise.
        if rng.random() < 0.35:
            other = rng.choice([s for s in SPECIALTIES if s.slug != primary.slug])
            session.execute(
                insert(doctor_specialty).values(
                    doctor_id=doctor.id,
                    specialty_id=specialties[other.slug].id,
                    is_primary=False,
                )
            )

        # Availability: weekdays always, plus some Saturday cover. Split into
        # two windows so the lunch break is expressed as the gap between them.
        for weekday in (
            Weekday.MONDAY,
            Weekday.TUESDAY,
            Weekday.WEDNESDAY,
            Weekday.THURSDAY,
            Weekday.FRIDAY,
        ):
            session.add(
                Availability(
                    doctor_id=doctor.id,
                    weekday=weekday,
                    start_time=dt.time(CLINIC_OPEN_HOUR, 0),
                    end_time=dt.time(12, 30),
                    effective_from=dt.date(2020, 1, 1),
                    is_active=True,
                )
            )
            session.add(
                Availability(
                    doctor_id=doctor.id,
                    weekday=weekday,
                    start_time=dt.time(13, 30),
                    end_time=dt.time(CLINIC_CLOSE_HOUR, 0),
                    effective_from=dt.date(2020, 1, 1),
                    is_active=True,
                )
            )
        if rng.random() < 0.4:
            session.add(
                Availability(
                    doctor_id=doctor.id,
                    weekday=Weekday.SATURDAY,
                    start_time=dt.time(9, 0),
                    end_time=dt.time(13, 0),
                    effective_from=dt.date(2020, 1, 1),
                    is_active=True,
                )
            )
        doctors.append(doctor)

    session.commit()
    log.info(
        "seeded clinic, %d specialties, %d rooms, %d doctors",
        len(SPECIALTIES),
        6,
        len(doctors),
    )
    return clinic, specialties, doctors


def seed_patients(
    session: Session, fake: Faker, rng: random.Random, n_patients: int
) -> list[tuple[int, float]]:
    """Create patients and return (id, latent no-show offset) pairs.

    The latent offset is the mechanism that makes a patient's history
    predictive of their future. It is never written to the database — only its
    *consequences* are, exactly as in reality, where you observe behaviour and
    must infer the propensity.
    """
    rows = []
    for _ in range(n_patients):
        rows.append(
            {
                "first_name": fake.first_name(),
                "last_name": fake.last_name(),
                "date_of_birth": fake.date_of_birth(minimum_age=1, maximum_age=95),
                "phone": fake.phone_number()[:32],
                "email": fake.unique.email(),
            }
        )
    session.execute(insert(Patient), rows)
    session.commit()

    ids = list(session.execute(select(Patient.id).order_by(Patient.id)).scalars())
    baseline_logit = _logit(PATIENT_PROPENSITY_MEAN)
    out = []
    for pid in ids:
        propensity = rng.betavariate(PATIENT_PROPENSITY_ALPHA, PATIENT_PROPENSITY_BETA)
        propensity = min(max(propensity, 0.01), 0.95)
        out.append((pid, _logit(propensity) - baseline_logit))
    log.info("seeded %d patients", len(out))
    return out


def generate_appointments(
    session: Session,
    rng: random.Random,
    clinic: Clinic,
    specialties: dict[str, Specialty],
    doctors: list[Doctor],
    patients: list[tuple[int, float]],
    start_date: dt.date,
    end_date: dt.date,
    today: dt.date,
    batch_size: int = 2000,
) -> int:
    # Which doctors can serve each specialty, from the junction table.
    doctor_ids_by_specialty: dict[int, list[int]] = {}
    for spec_id, doc_id in session.execute(
        select(doctor_specialty.c.specialty_id, doctor_specialty.c.doctor_id)
    ):
        doctor_ids_by_specialty.setdefault(spec_id, []).append(doc_id)

    calendar = DoctorCalendar()
    seen_patients: set[int] = set()
    spec_by_slug = {s.slug: s for s in SPECIALTIES}

    pending: list[dict] = []
    total = 0
    skipped = 0

    date = start_date
    while date <= end_date:
        weekday = date.isoweekday()
        for slug, spec_row in specialties.items():
            spec = spec_by_slug[slug]
            eligible = doctor_ids_by_specialty.get(spec_row.id, [])
            if not eligible:
                continue
            for hour in range(CLINIC_OPEN_HOUR, CLINIC_CLOSE_HOUR):
                lam = expected_volume(spec, date, hour)
                if lam <= 0:
                    continue
                # Poisson sampling via Knuth's method; lambda is small here.
                n = _poisson(rng, lam)
                for _ in range(n):
                    patient_id, patient_offset = rng.choice(patients)
                    is_new_patient = patient_id not in seen_patients
                    seen_patients.add(patient_id)

                    urgency = sample_urgency(rng)
                    lead_days = sample_lead_days(rng, urgency)
                    duration = sample_duration(rng, spec, is_new_patient)

                    minute = rng.choice([0, 15, 30, 45])
                    start = dt.time(hour, minute)
                    doctor_id = rng.choice(eligible)
                    if not calendar.try_book(doctor_id, date, start, duration):
                        # Try the other eligible doctors before giving up. A
                        # skipped appointment is fine and realistic (the clinic
                        # was full), but silently skipping most of them would
                        # flatten the demand signal, so validate_data.py checks
                        # the skip rate.
                        placed = False
                        for alt in rng.sample(eligible, k=len(eligible)):
                            if calendar.try_book(alt, date, start, duration):
                                doctor_id = alt
                                placed = True
                                break
                        if not placed:
                            skipped += 1
                            continue

                    end_minutes = hour * 60 + minute + duration
                    end = dt.time(end_minutes // 60, end_minutes % 60)

                    booked_date = date - dt.timedelta(days=lead_days)
                    booked_at = dt.datetime.combine(
                        booked_date,
                        dt.time(rng.randrange(8, 18), rng.randrange(0, 60)),
                        tzinfo=dt.UTC,
                    )
                    appt_start_dt = dt.datetime.combine(date, start, tzinfo=dt.UTC)
                    if booked_at > appt_start_dt:  # honours the CHECK constraint
                        booked_at = appt_start_dt - dt.timedelta(hours=1)

                    status = _resolve_status(
                        rng=rng,
                        date=date,
                        today=today,
                        lead_days=lead_days,
                        weekday=weekday,
                        hour=hour,
                        patient_offset=patient_offset,
                        is_new_patient=is_new_patient,
                        urgency=urgency,
                    )

                    pending.append(
                        {
                            "clinic_id": clinic.id,
                            "doctor_id": doctor_id,
                            "patient_id": patient_id,
                            "specialty_id": spec_row.id,
                            "appointment_date": date,
                            "start_time": start,
                            "end_time": end,
                            "booked_at": booked_at,
                            "status": status,
                            "urgency": urgency,
                            "is_new_patient": is_new_patient,
                            "room_id": None,
                        }
                    )
                    if len(pending) >= batch_size:
                        session.execute(insert(Appointment), pending)
                        session.commit()
                        total += len(pending)
                        log.info("inserted %d appointments", total)
                        pending.clear()
        date += dt.timedelta(days=1)

    if pending:
        session.execute(insert(Appointment), pending)
        session.commit()
        total += len(pending)

    log.info("generated %d appointments (%d skipped: clinic full)", total, skipped)
    return total


def _resolve_status(
    *,
    rng: random.Random,
    date: dt.date,
    today: dt.date,
    lead_days: int,
    weekday: int,
    hour: int,
    patient_offset: float,
    is_new_patient: bool,
    urgency: Urgency,
) -> AppointmentStatus:
    """Future appointments are simply scheduled; past ones get an outcome.

    Cancellation is decided first, because a cancelled appointment cannot also
    be a no-show — conflating the two would corrupt the no-show label the
    Phase 3 classifier trains on.
    """
    if date >= today:
        # Some future appointments are already cancelled.
        if rng.random() < cancel_probability(lead_days) * 0.5:
            return AppointmentStatus.CANCELLED
        return AppointmentStatus.SCHEDULED

    if rng.random() < cancel_probability(lead_days):
        return AppointmentStatus.CANCELLED

    p_no_show = no_show_probability(
        lead_days=lead_days,
        weekday=weekday,
        hour=hour,
        patient_offset=patient_offset,
        is_new_patient=is_new_patient,
        urgency=urgency,
    )
    return AppointmentStatus.NO_SHOW if rng.random() < p_no_show else AppointmentStatus.COMPLETED


def _poisson(rng: random.Random, lam: float) -> int:
    """Knuth's algorithm. Fine for the small lambdas used here (< 10)."""
    if lam <= 0:
        return 0
    limit = math.exp(-lam)
    k = 0
    p = 1.0
    while True:
        p *= rng.random()
        if p <= limit:
            return k
        k += 1
        if k > 50:  # guard against pathological lambda
            return k


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--months", type=int, default=12, help="months of history to generate")
    parser.add_argument("--future-days", type=int, default=30, help="days of future bookings")
    parser.add_argument("--doctors", type=int, default=8)
    parser.add_argument("--patients", type=int, default=1500)
    parser.add_argument("--seed", type=int, default=20260821)
    parser.add_argument("--reset", action="store_true", help="truncate existing data first")
    args = parser.parse_args()

    rng = random.Random(args.seed)
    fake = Faker()
    Faker.seed(args.seed)

    today = dt.date.today()
    start_date = today - dt.timedelta(days=30 * args.months)
    end_date = today + dt.timedelta(days=args.future_days)

    engine = create_engine(settings.database_url_sync, future=True)
    with Session(engine) as session:
        if args.reset:
            reset_data(session)

        existing = session.execute(select(Clinic.id)).first()
        if existing and not args.reset:
            log.error("data already present; re-run with --reset to regenerate")
            return 1

        clinic, specialties, doctors = seed_reference_data(session, fake, rng, args.doctors)
        patients = seed_patients(session, fake, rng, args.patients)
        count = generate_appointments(
            session,
            rng,
            clinic,
            specialties,
            doctors,
            patients,
            start_date,
            end_date,
            today,
        )

    log.info("done: %d appointments across %s .. %s", count, start_date, end_date)
    log.info("next step: uv run python scripts/validate_data.py")
    return 0


