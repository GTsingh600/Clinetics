# Parameters (every value here is documented in the module docstring above)
# ---------------------------------------------------------------------------
CLINIC_OPEN_HOUR = 8
CLINIC_CLOSE_HOUR = 19  # exclusive; last appointment starts before this
SLOT_MINUTES = 15

B0_NO_SHOW = -2.30
B_LEAD = 0.42
B_NEW_PATIENT = 0.45
B_DOW: dict[int, float] = {1: 0.30, 2: -0.05, 3: -0.10, 4: 0.00, 5: 0.22, 6: 0.15, 7: 0.10}
B_URGENCY: dict[Urgency, float] = {
    Urgency.ROUTINE: 0.0,
    Urgency.URGENT: -0.70,
    Urgency.EMERGENCY: -1.40,
}
PATIENT_PROPENSITY_ALPHA = 2.0
PATIENT_PROPENSITY_BETA = 8.0
PATIENT_PROPENSITY_MEAN = PATIENT_PROPENSITY_ALPHA / (
    PATIENT_PROPENSITY_ALPHA + PATIENT_PROPENSITY_BETA
)

B0_CANCEL = -2.60
B_LEAD_CANCEL = 0.30

WEEKDAY_MULT: dict[int, float] = {1: 1.35, 2: 1.05, 3: 1.00, 4: 1.02, 5: 0.95, 6: 0.45, 7: 0.10}
SEASONAL_AMPLITUDE = 0.15

URGENCY_MIX: list[tuple[Urgency, float]] = [
    (Urgency.ROUTINE, 0.80),
    (Urgency.URGENT, 0.16),
    (Urgency.EMERGENCY, 0.04),
]

NEW_PATIENT_EXTRA_MINUTES = 8
DURATION_SIGMA = 0.28


@dataclass(frozen=True)
class SpecialtySpec:
    name: str
    slug: str
    base_duration: int
    base_daily_volume: float
    # Relative weight per clock hour; normalised at use.
    hour_weights: dict[int, float] = field(default_factory=dict)


def _morning_weighted() -> dict[int, float]:
    """Peaks 09:00-11:00, tapering through the afternoon."""
    return {h: max(0.05, 1.6 - 0.11 * (h - 9) ** 2 * 0.35) for h in range(8, 19)}


def _evening_weighted() -> dict[int, float]:
    """Dermatology: patients come after work. Peaks 16:00-18:00."""
    return {h: max(0.05, 0.35 + 0.14 * (h - 8)) for h in range(8, 19)}


def _bimodal() -> dict[int, float]:
    """Paediatrics: a morning peak and an after-school peak."""
    out = {}
    for h in range(8, 19):
        morning = math.exp(-((h - 9.5) ** 2) / 2.2)
        afternoon = math.exp(-((h - 15.5) ** 2) / 2.6)
        out[h] = 0.15 + morning + 0.9 * afternoon
    return out


SPECIALTIES: list[SpecialtySpec] = [
    SpecialtySpec("Cardiology", "cardiology", 35, 7.0, _morning_weighted()),
    SpecialtySpec("Dermatology", "dermatology", 20, 6.0, _evening_weighted()),
    SpecialtySpec("General Practice", "general-practice", 15, 14.0, _morning_weighted()),
    SpecialtySpec("Orthopedics", "orthopedics", 30, 5.5, _morning_weighted()),
    SpecialtySpec("Pediatrics", "pediatrics", 25, 8.0, _bimodal()),
]


# ---------------------------------------------------------------------------
# Model functions
# ---------------------------------------------------------------------------
def _logit(p: float) -> float:
    return math.log(p / (1.0 - p))


def _sigmoid(x: float) -> float:
    return 1.0 / (1.0 + math.exp(-x))


def _hour_effect(hour: int) -> float:
    """Piecewise-linear no-show effect by hour: high early, dip midday, high late."""
    if hour <= 12:
        # 08:00 -> +0.34 down to 12:00 -> -0.12
        return 0.34 + (hour - 8) * (-0.46 / 4.0)
    # 12:00 -> -0.12 up to 18:00 -> +0.40
    return -0.12 + (hour - 12) * (0.52 / 6.0)


def no_show_probability(
    *,
    lead_days: int,
    weekday: int,
    hour: int,
    patient_offset: float,
    is_new_patient: bool,
    urgency: Urgency,
) -> float:
    logit_p = (
        B0_NO_SHOW
        + B_LEAD * math.log1p(lead_days)
        + B_DOW[weekday]
        + _hour_effect(hour)
        + patient_offset
        + B_NEW_PATIENT * float(is_new_patient)
        + B_URGENCY[urgency]
    )
    return _sigmoid(logit_p)


def cancel_probability(lead_days: int) -> float:
    return _sigmoid(B0_CANCEL + B_LEAD_CANCEL * math.log1p(lead_days))


def sample_lead_days(rng: random.Random, urgency: Urgency) -> int:
    if urgency is Urgency.EMERGENCY:
        if rng.random() < 0.7:
            return 0
        return min(3, int(rng.gammavariate(1.0, 1.0)))
    if urgency is Urgency.URGENT:
        return min(14, int(rng.gammavariate(1.2, 2.0)))
    return min(90, int(rng.gammavariate(2.0, 7.0)))


def sample_duration(rng: random.Random, spec: SpecialtySpec, is_new_patient: bool) -> int:
    raw = rng.lognormvariate(math.log(spec.base_duration), DURATION_SIGMA)
    if is_new_patient:
        raw += NEW_PATIENT_EXTRA_MINUTES
    return int(max(10, min(120, round(raw / 5.0) * 5)))


def sample_urgency(rng: random.Random) -> Urgency:
    r = rng.random()
    cumulative = 0.0
    for urgency, weight in URGENCY_MIX:
        cumulative += weight
        if r < cumulative:
            return urgency
    return Urgency.ROUTINE


def seasonal_factor(date: dt.date) -> float:
    return 1.0 + SEASONAL_AMPLITUDE * math.sin(2 * math.pi * (date.timetuple().tm_yday - 20) / 365)


def expected_volume(spec: SpecialtySpec, date: dt.date, hour: int) -> float:
    weights = spec.hour_weights
    total = sum(weights.values())
    share = weights.get(hour, 0.0) / total if total else 0.0
    return spec.base_daily_volume * WEEKDAY_MULT[date.isoweekday()] * share * seasonal_factor(date)


# ---------------------------------------------------------------------------
# Slot bookkeeping — the exclusion constraint is real, so the generator must
# not attempt to double-book. Placement is explicit rather than hopeful.
# ---------------------------------------------------------------------------
class DoctorCalendar:
    """Tracks which 15-minute slots a doctor has taken on each date."""

    def __init__(self) -> None:
        self._taken: dict[tuple[int, dt.date], set[int]] = {}

    @staticmethod
    def _slot_index(t: dt.time) -> int:
        return (t.hour * 60 + t.minute) // SLOT_MINUTES

    def try_book(self, doctor_id: int, date: dt.date, start: dt.time, duration: int) -> bool:
        first = self._slot_index(start)
        n_slots = math.ceil(duration / SLOT_MINUTES)
        end_minutes = first * SLOT_MINUTES + n_slots * SLOT_MINUTES
        if end_minutes > CLINIC_CLOSE_HOUR * 60:
            return False
        key = (doctor_id, date)
        taken = self._taken.setdefault(key, set())
        wanted = set(range(first, first + n_slots))
        if wanted & taken:
            return False
        taken |= wanted
        return True


